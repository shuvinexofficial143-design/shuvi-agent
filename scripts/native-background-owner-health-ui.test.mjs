import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const lib=read("src-tauri/src/lib.rs");
const os=read("src-tauri/src/native_background_os_workers.rs");
const main=read("src/main.ts");
const types=read("src/types.ts");
const journal=read("src-tauri/src/native_background_admission.rs");
test("native owner status is read-only, schema-bound, and obtains real locked worker journal and independent SHA rehash",()=>{
 assert.match(lib,/fn native_background_readonly_status\(app:AppHandle\)->Result<NativeBackgroundOwnerStatus,String>/);
 assert.match(lib,/native_scheduler::background_os_workers::inspect_readonly_health\(&root\)\?/);
 assert.match(lib,/native_background_readonly_status,\\s*native_approved_parent_queue_status,\\s*review_native_scheduler_failure/);
 assert.match(lib,/process_liveness_verified:false/);
 assert.match(lib,/application_verified:false/);
 assert.match(lib,/safe_to_auto_retry:false/);
 assert.match(lib,/fs::symlink_metadata\(&root\)/);
 assert.match(os,/pub\(crate\) fn inspect_readonly_health/);
 assert.match(os,/serde::Serialize/);
 assert.match(os,/hash_readback::verify\(/);
 assert.match(journal,/pub\(super\) fn snapshot_detailed_at/);
 assert.match(os,/current_file_rehashed:reverified/);
 assert.match(os,/safe_to_auto_retry:false/);
 assert.doesNotMatch(lib.slice(lib.indexOf("fn native_background_readonly_status("),lib.indexOf("#[tauri::command]\nfn native_scheduler_status(")),/spawn_internal_readonly\(|std::process::Command|permission.*grant|retry_action\(|cancel_exact\(/);
});
test("frontend provides explicit read-only background health without giving process status any permission or replay authority",()=>{
 assert.match(types,/export type NativeBackgroundOwnerStatus/);
 assert.match(types,/processLivenessVerified: false/);
 assert.match(types,/applicationVerified: false/);
 assert.match(types,/safeToAutoRetry: false/);
 assert.match(main,/id="nativeBackgroundHealthSummary"/);
 assert.match(main,/id="nativeBackgroundHealthList"/);
 assert.match(main,/id="refreshNativeBackgroundHealth"/);
 assert.match(main,/invoke<NativeBackgroundOwnerStatus>\("native_background_readonly_status"\)/);
 assert.match(main,/nativeBackgroundReadPending/);
 assert.match(main,/result\.processLivenessVerified!==false/);
 assert.match(main,/result\.applicationVerified!==false/);
 assert.match(main,/result\.safeToAutoRetry!==false/);
 assert.match(main,/worker\.currentFileRehashed/);
 assert.match(main,/worker\.evidenceHealth\.replaceAll/);
 assert.match(main,/summary\.textContent="Background SHA workers: unavailable"/);
 assert.match(main,/list\.replaceChildren\(\)/);
 assert.match(main,/document\.createElement\("small"\)/);
 assert.match(main,/window\.setInterval\(\(\) => void refreshNativeBackgroundHealth\(\), 20000\)/);
 assert.doesNotMatch(main.slice(main.indexOf("async function refreshNativeBackgroundHealth()"),main.indexOf("// Read-only display of UUID-bound Rust action history")),/innerHTML|prepare_tool|execute_action|cancel_running_action|retry_action/);
});
