import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const run=read("scripts/windows-m62-real-nsis-install-acceptance.mjs");
const ci=read(".github/workflows/ci.yml");
const smoke=read("scripts/check-installed-shuvi-worker.mjs");
const manifest=read("scripts/native-pinned-release-manifest.mjs");
test("M62 unsigned silent NSIS install is restricted to disposable GitHub Windows CI, with no arbitrary user paths",()=>{
 assert.match(run,/process\.platform!=="win32"/);
 assert.match(run,/process\.env\.CI!=="true"/);
 assert.match(run,/process\.env\.GITHUB_ACTIONS!=="true"/);
 assert.match(run,/process\.env\.RUNNER_TEMP/);
 assert.match(run,/process\.argv\.length!==2/);
 assert.match(run,/mkdtempSync\(join\(runnerTemp,"shuvi-m62-"\)\)/);
 assert.match(run,/verifyUnsignedReleaseEvidence\(\{manifestPath,sidecarPath:stage,nsisDir:nsis\}\)/);
 assert.match(run,/invocation\(installer,\["\/S","\/D="\+installDir\],180000\)/);
 assert.match(run,/shell:false/);
 assert.doesNotMatch(run,/Start-Process|Invoke-Expression|powershell\.exe|cmd\.exe|fetch\(|https?:\/\//);
});
test("M62 rehashes NSIS-installed fixed worker and actually runs independent immutable SHA evidence negative tests",()=>{
 assert.match(run,/verifyInstalledWorker\(\{manifestPath,installDir\}\)/);
 assert.match(run,/installedView\.manifest\.workerSha256!==verified\.workerSha256/);
 assert.match(run,/resolve\("scripts","check-installed-shuvi-worker\.mjs"\)/);
 assert.match(run,/proof\.exactReadOnlyShaProtocolVerified!==true/);
 assert.match(run,/proof\.shaMismatchRejected!==true/);
 assert.match(run,/proof\.uuidEvidenceReplayRejected!==true/);
 assert.match(run,/proof\.unknownCommandRejected!==true/);
 assert.match(run,/proof\.mainApplicationVerified!==false/);
 assert.match(run,/proof\.ownerDesktopEndToEndVerified!==false/);
 assert.match(smoke,/spawnSync\(installedWorker/);
 assert.match(manifest,/regular\(join\(dir,"shuvi\.exe"\)/);
});
test("M62 requires a unique real NSIS uninstaller and cleanup; cannot forge owner Windows or code signing",()=>{
 assert.match(run,/uninstallers\.length!==1/);
 assert.match(run,/invocation\(uninstaller,\["\/S"\],90000\)/);
 assert.match(run,/uninstalled=true/);
 assert.match(run,/rmSync\(root,\{recursive:true,force:true/);
 assert.match(run,/actualOwnerWindowsInstallationVerified:false/);
 assert.match(run,/mainDesktopAppLaunchedAndVerified:false/);
 assert.match(run,/authenticPublisherSignatureVerified:false/);
 assert.match(run,/blenderOrAdobeApplicationVerified:false/);
 assert.match(run,/autoRetryAuthorized:false/);
 assert.match(run,/m62-ephemeral-ci-install-witness\.json/);
 assert.match(ci,/M62 actually install the newly built NSIS on disposable Windows CI/);
 assert.match(ci,/run: node scripts\/windows-m62-real-nsis-install-acceptance\.mjs/);
 assert.match(ci,/path: \.shuvi-release\/\*\.json/);
 assert.doesNotMatch(ci,/path: .*bundle\/nsis.*\.exe/);
});
