import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const exe=read("src-tauri/src/bin/shuvi-readonly-hash-worker.rs");
const host=read("src-tauri/src/native_background_os_workers.rs");
const verify=read("src-tauri/src/native_background_hash_readback.rs");
const ledger=read("src-tauri/src/native_background_admission.rs");
const config=JSON.parse(read("src-tauri/tauri.conf.json"));
const sidecarConfig=JSON.parse(read("src-tauri/tauri.sha-sidecar.conf.json"));
const pkg=JSON.parse(read("package.json"));
const workflow=read(".github/workflows/ci.yml");
const builder=read("scripts/prepare-native-sha-sidecar.mjs");
const smoke=read("scripts/check-native-sha-sidecar.mjs");
test("only installed SHA-256 sidecar can run; no dynamic model executable or app IPC",()=>{
 assert.match(host,/dir\.join\("shuvi-readonly-hash-worker\.exe"\)/);
 assert.match(host,/fn run_trusted_sha256_with_guard</);
 assert.match(host,/spawn_admitted_readonly\(/);
 assert.match(host,/trusted_sidecar\(\)\?/);
 assert.match(host,/let bytes=hash_readback::verify\(&output,id,input,expected_sha256\)\?;/);
 assert.match(host,/admission::verified_sha_at\(root,id,pid\)\?;/);
 assert.match(host,/if exit_code!=0/);
 assert.doesNotMatch(host,/tauri::command|shell::|Command::new/);
 assert.match(exe,/args\.len\(\)!=6/);
 assert.match(exe,/sha\.len\(\)!=64/);
 assert.match(exe,/create_new\(true\)/);
 assert.match(exe,/share_mode\(0x1\)/);
 assert.match(exe,/read_count!=len/);
 assert.doesNotMatch(exe,/reqwest|std::process::Command|std::net|tauri::command/);
});
test("independent native host hash is required before durable terminal upgrade",()=>{
 assert.match(verify,/share_mode\(1\)/);
 assert.match(verify,/Sha256::new\(\)/);
 assert.match(verify,/actual!=expected/);
 assert.match(verify,/record\.input_sha256!=expected/);
 assert.match(verify,/record\.action_id!=id/);
 assert.match(verify,/host_rehashes_actual_file_and_detects_tamper_after_worker_exit/);
 assert.match(ledger,/pub\(super\) fn verified_sha_at\(/);
 assert.match(ledger,/sha256_verified/);
 assert.match(ledger,/item\.exit_code==Some\(0\)/);
 assert.match(ledger,/only_matching_os_exit_zero_may_become_independently_verified_sha/);
 assert.match(ledger,/app_verified:false/);
});
test("NSIS packaging builds exact Windows sidecar per target without untrusted downloads",()=>{
 assert.equal(config.bundle.externalBin,undefined);
 assert.deepEqual(sidecarConfig.bundle.externalBin,["binaries/shuvi-readonly-hash-worker"]);
 assert.equal(config.build.beforeBuildCommand,"npm run build");
 assert.equal(pkg.scripts["build:windows-installer"],"npm run prepare:sha-sidecar && tauri build --config src-tauri/tauri.sha-sidecar.conf.json");
 assert.equal(pkg.scripts["prepare:sha-sidecar"],"node scripts/prepare-native-sha-sidecar.mjs");
 assert.match(builder,/cargo/);
 assert.match(builder,/--locked/);
 assert.match(builder,/--release/);
 assert.match(builder,/--target/);
 assert.match(builder,/copyFileSync\(source,dest\)/);
 assert.match(builder,/windows-msvc/);
 assert.doesNotMatch(builder,/curl|Invoke-WebRequest|wget|https?:/);
 assert.match(workflow,/cargo build --manifest-path src-tauri\/Cargo\.toml --locked --bin shuvi-readonly-hash-worker/);
 assert.match(workflow,/node scripts\/check-native-sha-sidecar\.mjs/);
 assert.match(smoke,/spawnSync\(binary/);
 assert.match(smoke,/Wrong expected digest/);
});
